"""Generate the scratch CODEX_HOME hook configuration (throwaway harness).

Writes ``hooks.json`` (the User-layer hook declaration Codex reads from
``$CODEX_HOME/hooks.json``) and, when requested, the scratch home's
``config.toml``.

The v1 event set subscribes all 14 Codex hook events with one synchronous
command handler each, invoking ``emit_hook.py``. Timeouts are 5 s for every
event except ``SessionEnd``, which uses 2 s inside Codex's 1-3 s clamp
(``codex-rs/hooks/src/events/session_end.rs``). Matchers are deliberately
omitted: an absent matcher matches all occurrences, and Codex drops matcher
values on events that do not support them when computing the trust hash
(``codex-rs/hooks/src/events/common.rs``).

The generated ``config.toml`` pre-trusts the scratch workload directory
(``[projects."<workdir>"] trust_level = "trusted"``) because Codex 0.162+
shows a workspace-trust screen under bypass in untrusted git-less workdirs,
and suppresses the full-access warning notice. Approval-policy and
sandbox-mode settings belong to the launch flags, not this file.
"""

from __future__ import annotations

import argparse
import json
import shlex
import sys
from pathlib import Path
from typing import Any

EVENT_NAMES: tuple[str, ...] = (
    "PreModelRequest",
    "PostModelRequest",
    "PreToolUse",
    "PermissionRequest",
    "PostToolUse",
    "PreCompact",
    "PostCompact",
    "SessionStart",
    "SessionEnd",
    "UserPromptSubmit",
    "SubagentStart",
    "SubagentStop",
    "Stop",
    "Interrupt",
)
DEFAULT_TIMEOUT_SECONDS = 5
SESSION_END_TIMEOUT_SECONDS = 2
DEFAULT_EMITTER_NAME = "emit_hook.py"


def build_command(*, python_executable: str, emitter: Path) -> str:
    """Return the shell command a hook handler executes for one event.

    Codex runs the string through ``<shell> -c``; both parts are POSIX
    shell-quoted so paths containing spaces or metacharacters stay intact.
    """

    return f"{shlex.quote(python_executable)} {shlex.quote(str(emitter))}"


def build_hooks_document(
    *,
    command: str,
    timeout_seconds: int = DEFAULT_TIMEOUT_SECONDS,
    session_end_timeout_seconds: int = SESSION_END_TIMEOUT_SECONDS,
) -> dict[str, Any]:
    """Build the ``hooks.json`` document subscribing all 14 events.

    Parameters
    ----------
    command:
        Shell command executed for every handler.
    timeout_seconds:
        Timeout for the 13 events outside Codex's SessionEnd clamp.
    session_end_timeout_seconds:
        Timeout for ``SessionEnd``; Codex clamps it to 1-3 s.

    Returns
    -------
    dict
        ``{"hooks": {<Event>: [{"hooks": [<handler>]}]}}`` with no matchers.
    """

    if not 1 <= session_end_timeout_seconds <= 3:
        raise ValueError("SessionEnd timeout must stay within Codex's 1-3 s clamp")
    if timeout_seconds < 1:
        raise ValueError("hook timeout must be at least 1 second")
    hooks: dict[str, Any] = {}
    for event_name in EVENT_NAMES:
        timeout = session_end_timeout_seconds if event_name == "SessionEnd" else timeout_seconds
        hooks[event_name] = [
            {
                "hooks": [
                    {
                        "type": "command",
                        "command": command,
                        "timeout": timeout,
                        "async": False,
                    }
                ]
            }
        ]
    return {"hooks": hooks}


def _toml_basic_string(value: str) -> str:
    """Quote one value as a TOML basic string (used for quoted table keys)."""

    escaped = (
        value.replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\t", "\\t")
    )
    return f'"{escaped}"'


def build_config_toml(*, workdir: Path) -> str:
    """Build the scratch ``config.toml`` content for one workload directory.

    The path is emitted as a quoted TOML key. It should be absolute: Codex
    keys project trust by canonical path, and the runner always passes the
    absolute scratch workload.
    """

    return (
        "# Generated by scripts/explore/codex-hook-observation/observer_hooks.py\n"
        "# Scratch CODEX_HOME for one hook-capture run; safe to delete.\n"
        "\n"
        f"[projects.{_toml_basic_string(str(workdir))}]\n"
        'trust_level = "trusted"\n'
        "\n"
        "[notice]\n"
        "hide_full_access_warning = true\n"
    )


def main(argv: list[str] | None = None) -> int:
    """CLI entrypoint: write hooks.json and optionally the scratch config.toml."""

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, required=True, help="output hooks.json path")
    parser.add_argument(
        "--emitter",
        type=Path,
        default=None,
        help=f"emit_hook.py path (default: sibling {DEFAULT_EMITTER_NAME})",
    )
    parser.add_argument(
        "--python",
        default=sys.executable,
        help="Python interpreter used in handler commands (default: current)",
    )
    parser.add_argument(
        "--workdir",
        type=Path,
        default=None,
        help="workload directory to pre-trust in config.toml (absolute recommended)",
    )
    parser.add_argument(
        "--config-out",
        type=Path,
        default=None,
        help="config.toml output path (default with --workdir: <out parent>/config.toml)",
    )
    args = parser.parse_args(argv)

    emitter = args.emitter or (Path(__file__).resolve().parent / DEFAULT_EMITTER_NAME)
    if not emitter.is_file():
        parser.error(f"emitter does not exist: {emitter}")
    if args.config_out is not None and args.workdir is None:
        parser.error("--config-out requires --workdir")

    command = build_command(python_executable=args.python, emitter=emitter.resolve())
    document = build_hooks_document(command=command)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(document, indent=2) + "\n", encoding="utf-8")
    print(str(args.out))

    if args.workdir is not None:
        config_out = args.config_out or (args.out.parent / "config.toml")
        config_out.parent.mkdir(parents=True, exist_ok=True)
        config_out.write_text(build_config_toml(workdir=args.workdir.resolve()), encoding="utf-8")
        print(str(config_out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
